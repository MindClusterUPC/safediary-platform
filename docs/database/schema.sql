-- =====================================================================
-- 8. PAYMENTS & PAYOUTS: payment intents, subscriptions, ledger, payouts
-- =====================================================================

-- Idempotent payment charges for sessions or Premium subscriptions.
CREATE TABLE payments.payment_intents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose             VARCHAR(20)    NOT NULL CHECK (purpose IN ('APPOINTMENT', 'SUBSCRIPTION')),
    subject_id          BIGINT         NOT NULL,                     -- appointment_id or subscription_id (no FK: other context)
    payer_account_id    BIGINT         NOT NULL,                     -- -> iam.accounts (patient) (no FK: other context)
    amount              NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    currency            CHAR(3)        NOT NULL DEFAULT 'PEN',
    idempotency_key     VARCHAR(128)   NOT NULL UNIQUE,
    provider_reference  VARCHAR(255)   UNIQUE,
    status              VARCHAR(20)    NOT NULL DEFAULT 'CREATED'
                        CHECK (status IN ('CREATED', 'PENDING', 'APPROVED', 'FAILED', 'REFUNDED')),
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payment_intents_subject ON payments.payment_intents (purpose, subject_id);
CREATE INDEX ix_payment_intents_payer ON payments.payment_intents (payer_account_id, created_at DESC);

-- Premium subscription status and validity period for patients.
CREATE TABLE payments.subscriptions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_account_id  BIGINT      NOT NULL UNIQUE,                 -- -> iam.accounts (no FK: other context)
    plan                VARCHAR(20) NOT NULL DEFAULT 'BASICO'
                        CHECK (plan IN ('BASICO', 'PREMIUM')),
    active_until        TIMESTAMPTZ,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Official payment receipts issued upon approved payment intents.
CREATE TABLE payments.receipts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_intent_id  BIGINT       NOT NULL UNIQUE REFERENCES payments.payment_intents (id) ON DELETE CASCADE,
    receipt_number     VARCHAR(64)  NOT NULL UNIQUE,
    file_ref           VARCHAR(512),
    issued_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Financial movements ledger for psychologist session income and platform commissions.
CREATE TABLE payments.professional_ledger_movements (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_account_id  BIGINT         NOT NULL,                   -- -> iam.accounts (specialist) (no FK: other context)
    appointment_id        BIGINT         NOT NULL,                   -- -> care_scheduling.appointments (no FK: other context)
    gross_amount          NUMERIC(10, 2) NOT NULL CHECK (gross_amount >= 0),
    commission_amount     NUMERIC(10, 2) NOT NULL CHECK (commission_amount >= 0),
    net_amount            NUMERIC(10, 2) NOT NULL CHECK (net_amount >= 0),
    status                VARCHAR(20)    NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'AVAILABLE', 'WITHDRAWN')),
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ledger_amounts CHECK (gross_amount = commission_amount + net_amount)
);
CREATE INDEX ix_ledger_clinician_status ON payments.professional_ledger_movements (clinician_account_id, status);

-- Tokenized payout accounts registered by psychologists.
CREATE TABLE payments.payout_methods (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_account_id  BIGINT       NOT NULL,                     -- -> iam.accounts (specialist) (no FK: other context)
    provider_token_ref    VARCHAR(255) NOT NULL,
    bank_name             VARCHAR(100),
    account_masked        VARCHAR(30),
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_payout_methods_clinician ON payments.payout_methods (clinician_account_id) WHERE status = 'ACTIVE';

-- Payout requests from clinician available ledger balance.
CREATE TABLE payments.payout_requests (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_account_id  BIGINT         NOT NULL,                   -- -> iam.accounts (specialist) (no FK: other context)
    payout_method_id      BIGINT         NOT NULL REFERENCES payments.payout_methods (id) ON DELETE RESTRICT,
    amount                NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    currency              CHAR(3)        NOT NULL DEFAULT 'PEN',
    status                VARCHAR(20)    NOT NULL DEFAULT 'REQUESTED'
                          CHECK (status IN ('REQUESTED', 'PROCESSING', 'COMPLETED', 'REJECTED')),
    provider_reference    VARCHAR(255),
    requested_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    processed_at          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payout_requests_clinician ON payments.payout_requests (clinician_account_id, requested_at DESC);
