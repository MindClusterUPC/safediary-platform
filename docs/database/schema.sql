-- =====================================================================
-- ASSISTANTAI: conversations, emotion, distortions, risk, clinical summary
-- (already implemented in the backend; keep column names in sync with the JPA entities)
-- =====================================================================

CREATE TABLE assistantai.conversation_sessions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT      NOT NULL,
    started_at    TIMESTAMPTZ NOT NULL,
    ended_at      TIMESTAMPTZ,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'CLOSED', 'CRISIS_TRIGGERED')),
    current_tone  VARCHAR(20) NOT NULL CHECK (current_tone IN ('EMPATHIC', 'REFLECTIVE', 'ANALYTICAL', 'CALM')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_conversation_sessions_account ON assistantai.conversation_sessions (account_id, started_at DESC);

CREATE TABLE assistantai.conversation_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT      NOT NULL REFERENCES assistantai.conversation_sessions (id) ON DELETE CASCADE,
    sender       VARCHAR(10) NOT NULL CHECK (sender IN ('USER', 'AI')),
    content      TEXT        NOT NULL,
    emotion_tag  VARCHAR(20) CHECK (emotion_tag IN
                 ('APPREHENSION', 'ACCEPTANCE', 'ANNOYANCE', 'VIGILANCE', 'PENSIVENESS', 'SERENITY', 'JOY', 'SADNESS', 'FEAR')),
    sent_at      TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_conversation_messages_session ON assistantai.conversation_messages (session_id, sent_at);

CREATE TABLE assistantai.cognitive_distortions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  BIGINT       NOT NULL REFERENCES assistantai.conversation_messages (id) ON DELETE CASCADE,
    type        VARCHAR(30)  NOT NULL CHECK (type IN
                ('CATASTROPHIZING', 'OVERGENERALIZATION', 'ALL_OR_NOTHING', 'EMOTIONAL_REASONING', 'MENTAL_FILTER')),
    evidence    VARCHAR(300),
    confidence  DOUBLE PRECISION NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_cognitive_distortions_message ON assistantai.cognitive_distortions (message_id);

-- One assessment per evaluated user message (a session has many).
CREATE TABLE assistantai.risk_assessments (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id                 BIGINT       NOT NULL REFERENCES assistantai.conversation_sessions (id) ON DELETE CASCADE,
    message_id                 BIGINT       REFERENCES assistantai.conversation_messages (id) ON DELETE SET NULL,
    risk_score                 DOUBLE PRECISION NOT NULL CHECK (risk_score BETWEEN 0 AND 1),
    risk_level                 VARCHAR(10)  NOT NULL CHECK (risk_level IN ('LOW', 'MODERATE', 'HIGH', 'CRITICAL')),
    trigger_keywords           VARCHAR(500),
    crisis_protocol_activated  BOOLEAN      NOT NULL DEFAULT FALSE,
    assessed_at                TIMESTAMPTZ  NOT NULL,
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_risk_assessments_session ON assistantai.risk_assessments (session_id, assessed_at DESC);
CREATE INDEX ix_risk_assessments_crisis ON assistantai.risk_assessments (assessed_at DESC)
    WHERE crisis_protocol_activated;

-- Weekly summary for the specialist. Only visible with an iam.consents scope AI_CLINICAL_SUMMARIES.
CREATE TABLE assistantai.clinical_summaries (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id           BIGINT       NOT NULL,
    period_start         DATE         NOT NULL,
    period_end           DATE         NOT NULL,
    dominant_emotions    VARCHAR(200),
    key_triggers         TEXT,
    synthesis_narrative  TEXT         NOT NULL,
    highlights           TEXT,
    generated_at         TIMESTAMPTZ  NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_clinical_summaries_period CHECK (period_end >= period_start),
    CONSTRAINT ux_clinical_summaries_period UNIQUE (account_id, period_start, period_end)
);

-- =====================================================================
-- COMMUNITIES: anonymous real-time support rooms (absorbs the old "Rooms" context)
-- Only alias ids appear here. No account_id, no raw audio.
-- =====================================================================

CREATE TABLE communities.rooms (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_alias_id         BIGINT       NOT NULL,          -- -> profiles.community_aliases
    title                 VARCHAR(100) NOT NULL,
    topic                 VARCHAR(60)  NOT NULL,
    description           TEXT,
    room_type             VARCHAR(20)  NOT NULL DEFAULT 'PEER'
                          CHECK (room_type IN ('PEER', 'PROFESSIONAL_GROUP')),  -- group session led by a psychologist
    lifecycle             VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED'
                          CHECK (lifecycle IN ('SCHEDULED', 'OPEN', 'CLOSED', 'CANCELLED')),
    capacity              SMALLINT     NOT NULL CHECK (capacity BETWEEN 2 AND 200),
    time_limit_minutes    SMALLINT     CHECK (time_limit_minutes BETWEEN 5 AND 240),
    scheduled_at          TIMESTAMPTZ,
    opened_at             TIMESTAMPTZ,
    closed_at             TIMESTAMPTZ,
    version               INTEGER      NOT NULL DEFAULT 0,  -- optimistic locking (@Version)
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_rooms_lifecycle ON communities.rooms (lifecycle, scheduled_at);

CREATE TABLE communities.room_tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT      NOT NULL REFERENCES communities.rooms (id) ON DELETE CASCADE,
    tag         VARCHAR(40) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_room_tags UNIQUE (room_id, tag)
);

CREATE TABLE communities.participants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT      NOT NULL REFERENCES communities.rooms (id) ON DELETE CASCADE,
    alias_id    BIGINT      NOT NULL,
    role        VARCHAR(10) NOT NULL DEFAULT 'LISTENER' CHECK (role IN ('HOST', 'MODERATOR', 'SPEAKER', 'LISTENER')),
    status      VARCHAR(10) NOT NULL DEFAULT 'JOINED' CHECK (status IN ('JOINED', 'LEFT', 'REMOVED')),
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- An alias can be inside a room only once at a time.
CREATE UNIQUE INDEX ux_participants_present ON communities.participants (room_id, alias_id) WHERE status = 'JOINED';

CREATE TABLE communities.speaker_requests (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id               BIGINT      NOT NULL REFERENCES communities.rooms (id) ON DELETE CASCADE,
    participant_id        BIGINT      NOT NULL REFERENCES communities.participants (id) ON DELETE CASCADE,
    status                VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    resolved_by_alias_id  BIGINT,
    requested_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at           TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_speaker_requests_pending ON communities.speaker_requests (participant_id) WHERE status = 'PENDING';

CREATE TABLE communities.reactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT      NOT NULL REFERENCES communities.rooms (id) ON DELETE CASCADE,
    participant_id  BIGINT      NOT NULL REFERENCES communities.participants (id) ON DELETE CASCADE,
    reaction_type   VARCHAR(20) NOT NULL CHECK (reaction_type IN ('VIRTUAL_HUG', 'HEART', 'CLAP', 'SUPPORT')),
    sent_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_reactions_room ON communities.reactions (room_id, sent_at);

CREATE TABLE communities.moderation_cases (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id               BIGINT       NOT NULL REFERENCES communities.rooms (id) ON DELETE CASCADE,
    reporter_alias_id     BIGINT       NOT NULL,
    reported_alias_id     BIGINT       NOT NULL,
    reason                VARCHAR(30)  NOT NULL CHECK (reason IN ('HARASSMENT', 'HATE_SPEECH', 'SELF_HARM_CONTENT', 'SPAM', 'OTHER')),
    description           VARCHAR(1000),
    status                VARCHAR(10)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    action                VARCHAR(10)  CHECK (action IN ('NONE', 'MUTE', 'REMOVE', 'BLOCK')),
    resolved_by_alias_id  BIGINT,
    resolved_at           TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_moderation_cases_distinct CHECK (reporter_alias_id <> reported_alias_id)
);
CREATE INDEX ix_moderation_cases_open ON communities.moderation_cases (room_id) WHERE status = 'OPEN';

CREATE TABLE communities.blocks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_alias_id    BIGINT      NOT NULL,
    blocked_alias_id    BIGINT      NOT NULL,
    moderation_case_id  BIGINT      REFERENCES communities.moderation_cases (id) ON DELETE SET NULL,
    active              BOOLEAN     NOT NULL DEFAULT TRUE,
    deactivated_at      TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_blocks_distinct CHECK (blocker_alias_id <> blocked_alias_id)
);
CREATE UNIQUE INDEX ux_blocks_active_pair ON communities.blocks (blocker_alias_id, blocked_alias_id) WHERE active;

-- =====================================================================
-- ROUTINES (DailyCare): routines, reminders, writing prompts, SOS exercises
-- =====================================================================

CREATE TABLE routines.routines (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT       NOT NULL,
    routine_type  VARCHAR(20)  NOT NULL DEFAULT 'CUSTOM'
                  CHECK (routine_type IN ('CUSTOM', 'JOURNALING', 'MOOD_CHECK_IN', 'BREATHING')),  -- JOURNALING = diary reminder
    title         VARCHAR(100) NOT NULL,
    description   VARCHAR(500),
    target_time   TIME         NOT NULL,                  -- local time in the profile timezone
    days_of_week  SMALLINT[]   NOT NULL DEFAULT '{1,2,3,4,5,6,7}',
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_routines_days CHECK (days_of_week <@ ARRAY[1,2,3,4,5,6,7]::SMALLINT[] AND cardinality(days_of_week) > 0)
);
CREATE INDEX ix_routines_account ON routines.routines (account_id) WHERE active;

-- "Recordatorio de rutina enviado".
CREATE TABLE routines.scheduled_notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id      BIGINT       NOT NULL REFERENCES routines.routines (id) ON DELETE CASCADE,
    scheduled_for   TIMESTAMPTZ  NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'CANCELLED')),
    sent_at         TIMESTAMPTZ,
    failure_reason  VARCHAR(300),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_scheduled_notifications UNIQUE (routine_id, scheduled_for)
);
CREATE INDEX ix_scheduled_notifications_due ON routines.scheduled_notifications (scheduled_for) WHERE status = 'PENDING';

-- "Rutina marcada como completada".
CREATE TABLE routines.routine_completions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id    BIGINT      NOT NULL REFERENCES routines.routines (id) ON DELETE CASCADE,
    completed_on  DATE        NOT NULL,
    completed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_routine_completions UNIQUE (routine_id, completed_on)
);

-- "Prompt de escritura (asignado por el psicólogo) recibido / completado".
CREATE TABLE routines.writing_prompts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT        NOT NULL,
    assigned_by_account_id  BIGINT,                       -- NULL = system prompt; otherwise the specialist
    question                VARCHAR(500)  NOT NULL,
    answer_text             TEXT,
    status                  VARCHAR(10)   NOT NULL DEFAULT 'ASSIGNED' CHECK (status IN ('ASSIGNED', 'COMPLETED')),
    assigned_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    answered_at             TIMESTAMPTZ,
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_writing_prompts_answer CHECK ((status = 'COMPLETED') = (answer_text IS NOT NULL AND answered_at IS NOT NULL))
);
CREATE INDEX ix_writing_prompts_account ON routines.writing_prompts (account_id, status);

-- "Ejercicio de regulación rápida (SOS / Respiración) iniciado".
CREATE TABLE routines.sos_exercise_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT      NOT NULL,
    exercise_type     VARCHAR(20) NOT NULL CHECK (exercise_type IN ('BREATHING', 'GROUNDING', 'BODY_SCAN')),
    duration_seconds  INTEGER     CHECK (duration_seconds > 0),
    initiated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_sos_exercise_logs_account ON routines.sos_exercise_logs (account_id, initiated_at DESC);
