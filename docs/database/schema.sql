CREATE INDEX ix_entry_attachments_entry ON diary.entry_attachments (entry_id);

-- "Estado de ánimo diario registrado".
CREATE TABLE diary.mood_check_ins (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT      NOT NULL,
    emotion        VARCHAR(20) NOT NULL CHECK (emotion IN
