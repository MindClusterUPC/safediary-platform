-- Initial contact and coordination initiation between patient and psychologist.
CREATE TABLE care_scheduling.contact_requests (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_account_id    BIGINT      NOT NULL,                      -- -> iam.accounts (no FK: other context)
    clinician_profile_id  BIGINT      NOT NULL,                      -- -> clinician_directory.clinician_profiles (no FK: other context)
    status                VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CLOSED')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_contact_requests_patient ON care_scheduling.contact_requests (patient_account_id);
CREATE INDEX ix_contact_requests_clinician ON care_scheduling.contact_requests (clinician_profile_id);

-- Direct scheduling coordination chat (does not grant diary access).
CREATE TABLE care_scheduling.coordination_messages (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_request_id  BIGINT      NOT NULL REFERENCES care_scheduling.contact_requests (id) ON DELETE CASCADE,
    sender_account_id   BIGINT      NOT NULL,                        -- -> iam.accounts (no FK: other context)
    body_text           TEXT        NOT NULL,
    sent_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_coordination_messages_request ON care_scheduling.coordination_messages (contact_request_id, sent_at);

-- Clinician recurring weekly bookable availability slots.
CREATE TABLE care_scheduling.availability_slots (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_profile_id  BIGINT      NOT NULL,                      -- -> clinician_directory.clinician_profiles (no FK: other context)
    day_of_week           SMALLINT    NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- ISO: 1 = Monday
    start_time            TIME        NOT NULL,
    end_time              TIME        NOT NULL,
    is_active             BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_care_slot_time CHECK (end_time > start_time)
);
CREATE INDEX ix_availability_slots_clinician ON care_scheduling.availability_slots (clinician_profile_id) WHERE is_active;

-- Appointments: holds agreed schedule, amount captured, and confirmation status.
CREATE TABLE care_scheduling.appointments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_request_id    BIGINT         REFERENCES care_scheduling.contact_requests (id) ON DELETE SET NULL,
    patient_account_id    BIGINT         NOT NULL,                   -- -> iam.accounts (no FK: other context)
    clinician_profile_id  BIGINT         NOT NULL,                   -- -> clinician_directory.clinician_profiles (no FK: other context)
    starts_at             TIMESTAMPTZ    NOT NULL,
    ends_at               TIMESTAMPTZ    NOT NULL,
    timezone              VARCHAR(40)    NOT NULL DEFAULT 'America/Lima',
    agreed_amount         NUMERIC(10, 2) NOT NULL CHECK (agreed_amount >= 0),
    currency              CHAR(3)        NOT NULL DEFAULT 'PEN',
    status                VARCHAR(20)    NOT NULL DEFAULT 'REQUESTED'
                          CHECK (status IN ('REQUESTED', 'HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'COMPLETED')),
    payment_reference     VARCHAR(128),                              -- -> payments.payment_intents (no FK: other context)
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_appointment_time CHECK (ends_at > starts_at)
);
CREATE INDEX ix_appointments_clinician_time ON care_scheduling.appointments (clinician_profile_id, starts_at);
CREATE INDEX ix_appointments_patient ON care_scheduling.appointments (patient_account_id, starts_at DESC);

-- Temporary 1-hour reservation hold pending payment confirmation.
CREATE TABLE care_scheduling.slot_holds (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT      NOT NULL UNIQUE REFERENCES care_scheduling.appointments (id) ON DELETE CASCADE,
    expires_at      TIMESTAMPTZ NOT NULL,                            -- policy: holds slot for 60 minutes
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'EXPIRED', 'RELEASED', 'CONFIRMED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_slot_holds_active ON care_scheduling.slot_holds (expires_at) WHERE status = 'ACTIVE';

-- Execution and video call session for confirmed appointments.
CREATE TABLE care_scheduling.clinical_sessions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id     BIGINT       NOT NULL UNIQUE REFERENCES care_scheduling.appointments (id) ON DELETE CASCADE,
    provider_room_ref  VARCHAR(255),                                 -- WebRTC / video provider room identifier
    started_at         TIMESTAMPTZ,
    ended_at           TIMESTAMPTZ,
    status             VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED'
                       CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'NO_SHOW', 'CANCELLED')),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Access audit log for authorized emotional summaries retrieved prior to a session.
CREATE TABLE care_scheduling.summary_access_audits (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id        BIGINT       NOT NULL REFERENCES care_scheduling.appointments (id) ON DELETE CASCADE,
    clinician_account_id  BIGINT       NOT NULL,                     -- -> iam.accounts (no FK: other context)
