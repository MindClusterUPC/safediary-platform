                                 CHECK (ai_tone_preference IN ('EMPATHIC', 'REFLECTIVE', 'ANALYTICAL', 'CALM')),
    proactive_follow_up_enabled  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at                   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE profiles.notification_preferences (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id            BIGINT      NOT NULL UNIQUE REFERENCES profiles.user_profiles (id) ON DELETE CASCADE,
    push_enabled          BOOLEAN     NOT NULL DEFAULT TRUE,
    email_enabled         BOOLEAN     NOT NULL DEFAULT FALSE,
    quiet_hours_start     TIME,
    quiet_hours_end       TIME,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Public directory card of a specialist (verification itself lives in iam.specialist_verifications).
CREATE TABLE profiles.clinician_profiles (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id                BIGINT        NOT NULL UNIQUE,
    professional_title        VARCHAR(120)  NOT NULL,
    bio                       TEXT,
    years_of_experience       SMALLINT      CHECK (years_of_experience >= 0),
    session_duration_minutes  SMALLINT      NOT NULL DEFAULT 50 CHECK (session_duration_minutes > 0),
    hourly_rate               NUMERIC(10, 2) CHECK (hourly_rate >= 0),
    currency                  CHAR(3)       NOT NULL DEFAULT 'PEN',
    insurance_accepted        BOOLEAN       NOT NULL DEFAULT FALSE,
    published_in_directory    BOOLEAN       NOT NULL DEFAULT FALSE,
    rating_average            NUMERIC(3, 2) CHECK (rating_average BETWEEN 0 AND 5),
    review_count              INTEGER       NOT NULL DEFAULT 0 CHECK (review_count >= 0),
    created_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE profiles.clinician_specialties (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_profile_id  BIGINT      NOT NULL REFERENCES profiles.clinician_profiles (id) ON DELETE CASCADE,
    specialty             VARCHAR(80) NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_clinician_specialties UNIQUE (clinician_profile_id, specialty)
);

CREATE TABLE profiles.clinician_availability_windows (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_profile_id  BIGINT      NOT NULL REFERENCES profiles.clinician_profiles (id) ON DELETE CASCADE,
    day_of_week           SMALLINT    NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO: 1 = Monday
    start_time            TIME        NOT NULL,
    end_time              TIME        NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_availability_range CHECK (end_time > start_time)
);
CREATE INDEX ix_availability_clinician ON profiles.clinician_availability_windows (clinician_profile_id);

-- "Sincronización de calendario externo completada" (Google Calendar / Outlook).
CREATE TABLE profiles.calendar_connections (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinician_profile_id     BIGINT       NOT NULL REFERENCES profiles.clinician_profiles (id) ON DELETE CASCADE,
    provider                 VARCHAR(20)  NOT NULL CHECK (provider IN ('GOOGLE', 'OUTLOOK')),
    external_calendar_id     VARCHAR(255) NOT NULL,
    refresh_token_encrypted  BYTEA        NOT NULL,      -- encrypted by the application, never plain text
    status                   VARCHAR(20)  NOT NULL DEFAULT 'CONNECTED'
                             CHECK (status IN ('CONNECTED', 'DISCONNECTED', 'ERROR')),
    last_synced_at           TIMESTAMPTZ,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_calendar_connections UNIQUE (clinician_profile_id, provider)
);

CREATE TABLE profiles.saved_specialists (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id            BIGINT      NOT NULL REFERENCES profiles.user_profiles (id) ON DELETE CASCADE,
    clinician_profile_id  BIGINT      NOT NULL REFERENCES profiles.clinician_profiles (id) ON DELETE CASCADE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_saved_specialists UNIQUE (profile_id, clinician_profile_id)
);

-- The ONLY place that links an anonymous alias to a real account.
-- Communities stores alias_id only and never sees account_id.
CREATE TABLE profiles.community_aliases (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT      NOT NULL,
    handle             VARCHAR(40) NOT NULL,
    avatar_url         VARCHAR(512),
    voice_mask_preset  VARCHAR(20)  CHECK (voice_mask_preset IN ('NONE', 'LOW', 'HIGH', 'ROBOTIC')),
    active             BOOLEAN     NOT NULL DEFAULT TRUE,
    rotated_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_community_aliases_handle ON profiles.community_aliases (lower(handle));
CREATE UNIQUE INDEX ux_community_aliases_one_active ON profiles.community_aliases (account_id) WHERE active;

-- =====================================================================
-- DIARY: entries (text/voice), factors, attachments, mood, vault, streaks
-- =====================================================================

CREATE TABLE diary.private_vaults (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT       NOT NULL UNIQUE,
    pin_hash    VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE diary.diary_entries (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT       NOT NULL,
    vault_id                BIGINT       REFERENCES diary.private_vaults (id) ON DELETE SET NULL,  -- "Entrada movida a Bóveda Privada"
    entry_type              VARCHAR(10)  NOT NULL CHECK (entry_type IN ('TEXT', 'VOICE')),
    title                   VARCHAR(150),
    content                 TEXT,                         -- text, or transcription of a voice note
    audio_url               VARCHAR(512),
    audio_duration_seconds  INTEGER      CHECK (audio_duration_seconds > 0),
    transcription_status    VARCHAR(20)  CHECK (transcription_status IN ('PENDING', 'COMPLETED', 'FAILED')),
    primary_emotion         VARCHAR(20)  CHECK (primary_emotion IN
                            ('APPREHENSION', 'ACCEPTANCE', 'ANNOYANCE', 'VIGILANCE', 'PENSIVENESS', 'SERENITY', 'JOY', 'SADNESS', 'FEAR')),
    emotion_confirmed       BOOLEAN      NOT NULL DEFAULT FALSE,  -- Emotion Tag: suggested by AI until the user confirms
    emotional_intensity     SMALLINT     CHECK (emotional_intensity BETWEEN 1 AND 10),
    ai_reflection           TEXT,                         -- filled by "ReflectionGenerated" from AssistantAI
    is_sensitive            BOOLEAN      NOT NULL DEFAULT FALSE,
    status                  VARCHAR(10)  NOT NULL DEFAULT 'SAVED' CHECK (status IN ('DRAFT', 'SAVED', 'DELETED')),
    written_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_diary_entries_body CHECK (
        (entry_type = 'TEXT' AND content IS NOT NULL) OR (entry_type = 'VOICE' AND audio_url IS NOT NULL))
);
CREATE INDEX ix_diary_entries_account_written ON diary.diary_entries (account_id, written_at DESC)
    WHERE status <> 'DELETED';

CREATE TABLE diary.entry_tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    BIGINT      NOT NULL REFERENCES diary.diary_entries (id) ON DELETE CASCADE,
    tag         VARCHAR(40) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_entry_tags UNIQUE (entry_id, tag)
);

-- "Factor externo (clima, sueño, etc.) etiquetado a una entrada".
CREATE TABLE diary.external_factors (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id         BIGINT       NOT NULL UNIQUE REFERENCES diary.diary_entries (id) ON DELETE CASCADE,
    sleep_hours      NUMERIC(3, 1) CHECK (sleep_hours BETWEEN 0 AND 24),
    energy_level     VARCHAR(10)  CHECK (energy_level IN ('LOW', 'MEDIUM', 'HIGH')),
    stress_level     VARCHAR(10)  CHECK (stress_level IN ('LOW', 'MEDIUM', 'HIGH')),
    weather          VARCHAR(20)  CHECK (weather IN ('SUNNY', 'CLOUDY', 'RAINY', 'COLD', 'HOT')),
    caffeine_intake  VARCHAR(10)  CHECK (caffeine_intake IN ('NONE', 'LOW', 'MEDIUM', 'HIGH')),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- "Archivos multimedia asociados".
CREATE TABLE diary.entry_attachments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    BIGINT       NOT NULL REFERENCES diary.diary_entries (id) ON DELETE CASCADE,
    file_url    VARCHAR(512) NOT NULL,
    media_type  VARCHAR(100) NOT NULL,                   -- MIME type
